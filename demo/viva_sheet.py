"""Build docs/VIVA_QA.md (Step 14, decision D-058):

    python -m demo.viva_sheet

Part 1 = the hand-curated cross-cutting questions in docs/viva_top20_source.md.
Part 2 = every "Likely viva questions" section, extracted from docs/steps/STEP_*.md, so it never drifts
from the step documents. Re-run after editing any step doc.
"""
import re

from ml.data.load import PROJECT_ROOT

DOCS = PROJECT_ROOT / "docs"


def _order(p):
    """Numbered steps first (0, 1, ..., 8, 8B, ...), then extensions (STEP_E1, STEP_E2) by name."""
    m = re.search(r"STEP_(\d+)", p.name)
    return (0, int(m[1]), p.name) if m else (1, 0, p.name)


def step_sections():
    out = []
    for f in sorted((DOCS / "steps").glob("STEP_*.md"), key=_order):
        text = f.read_text(encoding="utf-8")
        title = text.splitlines()[0].lstrip("# ").strip()
        m = re.search(r"^## \d+\. Likely viva questions\s*\n(.*?)(?=^## )", text, re.S | re.M)
        if not m:
            raise SystemExit(f"{f.name}: no 'Likely viva questions' section")
        qs = re.findall(r"^\d+\. .*", m[1], re.M)
        out.append((title, f.name, qs))
    return out


def main():
    top = (DOCS / "viva_top20_source.md").read_text(encoding="utf-8").strip()
    n_top = len(re.findall(r"^\d+\. \*\*", top, re.M))
    steps = step_sections()
    n_steps = sum(len(q) for _, _, q in steps)
    parts = [f"# FraudNet-Synth: Viva Q&A sheet\n\nGenerated by `python -m demo.viva_sheet`: {n_top} cross-cutting "
             f"questions, then {n_steps} step-by-step questions extracted from the {len(steps)} step documents. "
             "Every number here comes from a saved run (see `docs/RESULTS_ANNEXURE.md`).\n",
             "## Part 1. The questions examiners are most likely to ask\n", top,
             "\n## Part 2. Step by step\n"]
    for title, fname, qs in steps:
        parts.append(f"### {title}\n*From [`{fname}`](steps/{fname})*\n\n" + "\n".join(qs) + "\n")
    (DOCS / "VIVA_QA.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"docs/VIVA_QA.md: {n_top} curated + {n_steps} step questions from {len(steps)} step docs")


if __name__ == "__main__":
    main()
